#pragma once

#include "SOLIS.h"
#include "SOLISBatch.h"

#include <QString>
#include <QStringList>

#include <vector>

class ccPointCloud;

namespace solis { struct ExposureOptions; struct ExposureReference; struct ExposureContextInfo; struct CrownExposureSummary; }

namespace solis
{

enum class ResultComponent
{
    Direct,
    Diffuse,
    Total
};

struct ResultField
{
    int index = -1;
    QString name;
    QString resultId;

    bool isValid() const { return index >= 0 && !name.isEmpty(); }
};

//! Persistent metadata record for one qSOLIS scalar field.
struct ResultRecord
{
    QString metadataKey;
    QString resultId;
    QString fieldName;
    QString runId;
    QString batchId;
    QString component;
    QString unit;
    QString createdUtc;
    int fieldIndex = -1;

    bool hasField() const { return fieldIndex >= 0; }
};

//! Persistent metadata record for a qSOLIS batch.
struct BatchRecord
{
    QString metadataKey;
    QString batchId;
    QString createdUtc;
    unsigned count = 0;
    unsigned storedResultCount = 0;
    double startDayOfYear = 0.0;
    double endDayOfYear = 0.0;
    double stepMinutes = 0.0;
};

//! Outcome of a cleanup operation.
struct CleanupStats
{
    unsigned fieldsRemoved = 0;
    unsigned metadataRecordsRemoved = 0;
    unsigned missingFields = 0;
    unsigned legacyFieldsRemoved = 0;

    bool changed() const
    {
        return fieldsRemoved != 0 || metadataRecordsRemoved != 0 || legacyFieldsRemoved != 0;
    }
};

//! Centralized result naming, allocation, persistent metadata and cleanup.
/**
 * SOLIS results stay on the original point/vertex cloud as independent scalar
 * fields. This avoids duplicating geometry while allowing many time points to
 * coexist in the same CloudCompare project.
 *
 * Full calculation settings are stored as qSOLIS metadata on the cloud, keyed
 * by a stable result UUID. The visible scalar-field name intentionally stays
 * compact and human-readable.
 */
class ResultManager
{
public:
    //! Creates a UUID shared by all fields generated by one SOLIS invocation.
    static QString NewRunId();

    //! Human-readable deterministic base name (before duplicate suffixing).
    static QString BaseFieldName(ResultComponent component,
                                 const CalculationOptions& options);

    //! Returns a non-colliding scalar-field name without deleting/overwriting old results.
    static QString UniqueFieldName(const ccPointCloud* cloud,
                                   const QString& baseName);

    //! Allocates a persistent result field and makes it the current scalar field.
    static bool CreateResultField(ccPointCloud* cloud,
                                  ResultComponent component,
                                  const CalculationOptions& options,
                                  ResultField& result);


    //! Allocates a persistent qSOLIS field with an explicit deterministic base name.
    static bool CreateNamedResultField(ccPointCloud* cloud,
                                       const QString& baseName,
                                       ResultField& result);

    //! Stores schema-v3 metadata for an exposure scalar field.
    static void StoreExposureMetadata(ccPointCloud* cloud,
                                      const ResultField& result,
                                      const QString& metric,
                                      const ExposureOptions& options,
                                      const ExposureReference& reference,
                                      const ExposureContextInfo& contextInfo,
                                      const QString& runId,
                                      const QString& entityName = QString());

    //! Stores the entity-level Crown Exposure Index summary for an exposure run.
    static void StoreCrownExposureMetadata(ccPointCloud* cloud,
                                           const CrownExposureSummary& summary,
                                           const ExposureOptions& options,
                                           const ExposureContextInfo& contextInfo,
                                           const QString& runId,
                                           const QString& entityName,
                                           const QStringList& sourceResultIds);

    //! Allocates a hidden temporary working field (used by TOTAL-only calculations).
    static bool CreateTemporaryField(ccPointCloud* cloud,
                                     ResultComponent component,
                                     const QString& runId,
                                     ResultField& result);

    //! Computes min/max, displays the field, and enables scalar-field display.
    static void FinalizeField(ccPointCloud* cloud, int index);

    //! Creates Total = max(0, Direct + Diffuse) as a new persistent scalar field.
    static bool CreateTotalField(ccPointCloud* cloud,
                                 int directIndex,
                                 int diffuseIndex,
                                 const CalculationOptions& options,
                                 ResultField& totalResult);

    //! Stores all settings for one persistent field in CloudCompare metadata.
    static void StoreMetadata(ccPointCloud* cloud,
                              const ResultField& result,
                              ResultComponent component,
                              const CalculationOptions& options,
                              const QString& runId,
                              const QString& entityName = QString(),
                              const BatchContext* batchContext = nullptr);

    //! Stores one summary record for the complete time-series batch.
    static void StoreBatchMetadata(ccPointCloud* cloud,
                                   const BatchContext& batchContext,
                                   const QString& entityName = QString());

    //! Enumerates metadata-backed qSOLIS result fields on a cloud.
    static std::vector<ResultRecord> Results(const ccPointCloud* cloud);

    //! Enumerates qSOLIS batch records and current stored-result counts.
    static std::vector<BatchRecord> Batches(const ccPointCloud* cloud);

    //! Returns the most recently stored run/batch identifiers, if any remain.
    static QString LastRunId(const ccPointCloud* cloud);
    static QString LastBatchId(const ccPointCloud* cloud);

    //! Counts legacy SOLIS-named fields that do not have qSOLIS result metadata.
    static unsigned LegacyFieldCount(const ccPointCloud* cloud);

    //! Metadata-first cleanup operations. Unrelated scalar fields are never touched.
    static CleanupStats RemoveRun(ccPointCloud* cloud, const QString& runId);
    static CleanupStats RemoveBatch(ccPointCloud* cloud, const QString& batchId);
    static CleanupStats RemoveAll(ccPointCloud* cloud);

    //! Explicit opt-in cleanup for old/pre-metadata fields whose names begin with "SOLIS ".
    static CleanupStats RemoveLegacyNamedFields(ccPointCloud* cloud);

    static QString ComponentName(ResultComponent component);
    static QString TemporalModeName(TemporalMode mode);
    static QString SpatialModeName(SpatialMode mode);
};

} // namespace solis
